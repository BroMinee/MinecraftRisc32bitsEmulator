void draw_char(int x, int y, char c, uint8_t r, uint8_t g, uint8_t b) {
    if (c < ' ' || c > '~') {
	return;
    }

    c -= ' ';

    for (int row = 0; row < 5; row++) {
        uint8_t line = font_5x7[(int)c][row];
        for (int col = 0; col < 6; col++) {
            if (line & (1 << (5 - col))) {
                write_pixel(x + col, y + row, r, g, b);
            }
        }
    }
}

void draw_string(int x, int y, const char *str, uint8_t r, uint8_t g, uint8_t b) {
    while (*str) {
        if (*str == '\n' || x + 6 > 64) {
            x = 0;
            y += 7;
            if (y + 7 > 64) break;
	    if(*str == '\n') {
	        str += 1;
		continue;
	    }
        }
        draw_char(x, y, *str, r, g, b);
        x += 7;
        str++;
    }
}

char *my_itoa(uint32_t value, char *s)
{
    uint32_t tmp = value;
    uint32_t nb_digits = 1;
    while (tmp > 9)
    {
        nb_digits *= 10;
        tmp /= 10;
    }

    uint32_t i = 0;
    for (; nb_digits != 0; i++)
    {
        s[i] = value / nb_digits + '0';
        value = value - nb_digits * (value / nb_digits);
        nb_digits /= 10;
    }
    return s;
}
